function generateEndUserPdf(doc: jsPDF, report: EndUserReport): void {
  let y = addHeader(doc, report.summary, "end-user");

  const pageWidth = doc.internal.pageSize.getWidth();

  // Score summary
  doc.setFontSize(14);
  doc.setTextColor(...COLORS.darkGray);
  doc.text("Accessibility Score Overview", 20, y);
  y += 10;

  doc.setFontSize(28);
  doc.setTextColor(...COLORS.primary);
  doc.text(`${report.score}/100`, pageWidth / 2, y, { align: "center" });
  y += 10;

  doc.setFontSize(14);
  doc.text(report.scoreLabel, pageWidth / 2, y, { align: "center" });
  y += 14;

  // Score interpretation
  let interpretation: string;
  if (report.score >= 90) {
    interpretation =
      "This website demonstrates excellent accessibility. Most users, including those who rely on assistive technologies, should be able to navigate and use the content effectively.";
  } else if (report.score >= 70) {
    interpretation =
      "This website has good overall accessibility but there are some areas that could be improved. Some users with disabilities may encounter occasional difficulties.";
  } else if (report.score >= 50) {
    interpretation =
      "This website needs accessibility improvements. Users who rely on assistive technologies such as screen readers or keyboard navigation may face significant barriers.";
  } else if (report.score >= 30) {
    interpretation =
      "This website has poor accessibility. Many users with disabilities will encounter serious barriers that prevent them from using the site effectively.";
  } else {
    interpretation =
      "This website has critical accessibility issues. The site is largely inaccessible to users who depend on assistive technologies, and immediate remediation is strongly recommended.";
  }

  const interpLines = doc.splitTextToSize(interpretation, pageWidth - 40);
  doc.setFontSize(10);
  doc.setTextColor(...COLORS.mediumGray);
  doc.text(interpLines, 20, y);
  y += interpLines.length * 5 + 10;

  // Category summaries
  doc.setFontSize(14);
  doc.setTextColor(...COLORS.darkGray);
  doc.text("Accessibility Categories", 20, y);
  y += 6;

  if (report.categories.length > 0) {
    const catBody = report.categories.map((c) => [
      c.name,
      `${c.score}/100`,
      String(c.issueCount),
      truncate(c.description, 80),
    ]);

    autoTable(doc, {
      startY: y,
      head: [["Category", "Score", "Issues", "Description"]],
      body: catBody,
      headStyles: {
        fillColor: COLORS.primary,
        textColor: COLORS.white,
        fontSize: 9,
        fontStyle: "bold",
      },
      bodyStyles: {
        fontSize: 8,
        textColor: COLORS.darkGray,
      },
      alternateRowStyles: {
        fillColor: COLORS.lightGray,
      },
      columnStyles: {
        0: { cellWidth: 35, fontStyle: "bold" },
        1: { cellWidth: 22 },
        2: { cellWidth: 18 },
        3: { cellWidth: "auto" },
      },
      margin: { left: 20, right: 20 },
    });
  }

  // Priority actions on new page
  if (report.priorities.length > 0) {
    doc.addPage();
    let priY = 20;

    doc.setFontSize(14);
    doc.setTextColor(...COLORS.darkGray);
    doc.text("Priority Actions", 20, priY);
    priY += 8;

    doc.setFontSize(10);
    doc.setTextColor(...COLORS.mediumGray);
    doc.text(
      "The following priorities are recommended to improve the accessibility of this website:",
      20,
      priY
    );
    priY += 10;

    for (let i = 0; i < report.priorities.length; i++) {
      doc.setFontSize(10);
      doc.setTextColor(...COLORS.darkGray);

      const lines = doc.splitTextToSize(
        `${i + 1}. ${report.priorities[i]}`,
        pageWidth - 40
      );
      doc.text(lines, 20, priY);
      priY += lines.length * 5 + 4;

      // Add page if running out of space
      if (priY > doc.internal.pageSize.getHeight() - 30) {
        doc.addPage();
        priY = 20;
      }
    }
  }

  addFooter(doc);
}

// ---------------------------------------------------------------------------
// Public API
// ---------------------------------------------------------------------------

export function exportToPdf(
  report: DeveloperReport | AuditorReport | EndUserReport,
  reportType: ReportType
): void {
  const doc = new jsPDF({
    orientation: "landscape",
    unit: "mm",
    format: "a4",
  });

  switch (reportType) {
    case "developer":
      generateDeveloperPdf(doc, report as DeveloperReport);
      break;
    case "auditor":
      generateAuditorPdf(doc, report as AuditorReport);
      break;
    case "end-user":
      generateEndUserPdf(doc, report as EndUserReport);
      break;
  }

  const filename = `awae-${reportType}-report-${getDateString()}.pdf`;
  doc.save(filename);
}
