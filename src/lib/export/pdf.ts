function generateAuditorPdf(doc: jsPDF, report: AuditorReport): void {
  let y = addHeader(doc, report.summary, "auditor");

  // Principle breakdown
  doc.setFontSize(14);
  doc.setTextColor(...COLORS.darkGray);
  doc.text("WCAG 2.2 Principle Breakdown", 20, y);
  y += 6;

  const principleBody = report.principleBreakdown.map((p) => [
    p.principle,
    String(p.totalCriteria),
    String(p.passedCriteria),
    String(p.failedCriteria),
    `${p.compliancePercentage.toFixed(1)}%`,
  ]);

  autoTable(doc, {
    startY: y,
    head: [["Principle", "Total Criteria", "Passed", "Failed", "Compliance"]],
    body: principleBody,
    headStyles: {
      fillColor: COLORS.primary,
      textColor: COLORS.white,
      fontSize: 9,
      fontStyle: "bold",
    },
    bodyStyles: {
      fontSize: 8,
      textColor: COLORS.darkGray,
    },
    alternateRowStyles: {
      fillColor: COLORS.lightGray,
    },
    margin: { left: 20, right: 20 },
    didParseCell(data) {
      if (data.section === "body" && data.column.index === 4) {
        const val = parseFloat(String(data.cell.raw));
        if (val >= 90) data.cell.styles.textColor = [34, 197, 94];
        else if (val >= 70) data.cell.styles.textColor = [132, 204, 22];
        else if (val >= 50) data.cell.styles.textColor = [245, 158, 11];
        else data.cell.styles.textColor = [239, 68, 68];
        data.cell.styles.fontStyle = "bold";
      }
    },
  });

  // Compliance Matrix on new page
  doc.addPage();
  let matrixY = 20;

  doc.setFontSize(14);
  doc.setTextColor(...COLORS.darkGray);
  doc.text("Compliance Matrix", 20, matrixY);
  matrixY += 6;

  const matrixBody = report.complianceMatrix.map((c) => [
    c.criterion,
    truncate(c.title, 40),
    c.level,
    c.principle,
    c.status === "pass" ? "Pass" : c.status === "fail" ? "Fail" : "Not Tested",
    String(c.violationCount),
  ]);

  autoTable(doc, {
    startY: matrixY,
    head: [
      ["Criterion", "Title", "Level", "Principle", "Status", "Violations"],
    ],
    body: matrixBody,
    headStyles: {
      fillColor: COLORS.primary,
      textColor: COLORS.white,
      fontSize: 8,
      fontStyle: "bold",
    },
    bodyStyles: {
      fontSize: 7,
      textColor: COLORS.darkGray,
    },
    alternateRowStyles: {
      fillColor: COLORS.lightGray,
    },
    columnStyles: {
      0: { cellWidth: 22 },
      1: { cellWidth: "auto" },
      2: { cellWidth: 15 },
      3: { cellWidth: 28 },
      4: { cellWidth: 22 },
      5: { cellWidth: 20 },
    },
    margin: { left: 20, right: 20 },
    didParseCell(data) {
      if (data.section === "body" && data.column.index === 4) {
        const status = String(data.cell.raw);
        if (status === "Pass") {
          data.cell.styles.textColor = [34, 197, 94];
          data.cell.styles.fontStyle = "bold";
        } else if (status === "Fail") {
          data.cell.styles.textColor = [239, 68, 68];
          data.cell.styles.fontStyle = "bold";
        } else {
          data.cell.styles.textColor = COLORS.mediumGray;
        }
      }
    },
  });

  // Violations table on new page
  doc.addPage();
  let violY = 20;

  doc.setFontSize(14);
  doc.setTextColor(...COLORS.darkGray);
  doc.text("Violations", 20, violY);
  violY += 6;

  if (report.violations.length === 0) {
    doc.setFontSize(11);
    doc.setTextColor(...COLORS.mediumGray);
    doc.text("No violations found.", 20, violY + 6);
  } else {
    const violBody = report.violations.map((v) => [
      v.ruleId,
      v.severity.charAt(0).toUpperCase() + v.severity.slice(1),
      `${v.wcagCriterion} (${v.wcagLevel})`,
      v.wcagPrinciple,
      String(v.instanceCount),
      truncate(v.formalDescription, 80),
    ]);

    autoTable(doc, {
      startY: violY,
      head: [
        [
          "Rule ID",
          "Severity",
          "WCAG",
          "Principle",
          "Instances",
          "Description",
        ],
      ],
      body: violBody,
      headStyles: {
        fillColor: COLORS.primary,
        textColor: COLORS.white,
        fontSize: 8,
        fontStyle: "bold",
      },
      bodyStyles: {
        fontSize: 7,
        textColor: COLORS.darkGray,
      },
      alternateRowStyles: {
        fillColor: COLORS.lightGray,
      },
      margin: { left: 20, right: 20 },
      didParseCell(data) {
        if (data.section === "body" && data.column.index === 1) {
          const raw = String(data.cell.raw).toLowerCase();
          data.cell.styles.textColor = severityColor(raw);
          data.cell.styles.fontStyle = "bold";
        }
      },
    });
  }

  addFooter(doc);
}

